#!/usr/bin/env python3
"""Render repository-owned package declarations from evaluated Nix modules."""

import argparse
import difflib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
DOCUMENT = ROOT / "docs/apps.md"
GROUPS = (
    ("Homebrew cask", "Desktop apps and fonts"),
    ("Mac App Store", "Mac App Store apps"),
    ("Homebrew formula", "Homebrew CLI tools"),
    ("Nix system", "Nix system tools and apps"),
    ("Home Manager", "Home Manager tools"),
)


def cell(value):
    return " ".join(value.split()).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def render(rows):
    merged = {}
    for row in rows:
        key = tuple(row[field] for field in ("manager", "name", "description", "declaration"))
        merged.setdefault(key, set()).add(row["host"])
    lines = [
        "# Managed apps and tools", "",
        "Generated from evaluated Nix declarations. Do not edit this file by hand.", "",
        "Regenerate with `make inventory`; verify with `make inventory-check`.", "",
        "Includes repository-owned Homebrew formulae, casks, Mac App Store apps, and explicit",
        "`environment.systemPackages` / `home.packages` declarations for every flake host.",
        "Upstream module defaults, dependencies, macOS built-ins, and tools installed by",
        "external runtimes (such as APM skills or npm MCP commands) are not package inventory entries.", "",
        "This describes desired configuration, not what is currently installed. Homebrew versions",
        "are machine-local; Nix pins are documented in [Nix toolchain](nix-toolchain.md).",
        "Descriptions come from Nix package metadata; a dash means no description is declared.",
        "Casks also include fonts and plugins, not only GUI apps.", "",
    ]
    for manager, title in GROUPS:
        entries = sorted((key, hosts) for key, hosts in merged.items() if key[0] == manager)
        lines += [f"## {title}", "", f"Managed by: {manager}.", "",
                  "| Name | Description | Hosts | Declaration |", "| --- | --- | --- | --- |"]
        for (_, name, description, declaration), hosts in entries:
            lines.append(f"| `{cell(name)}` | {cell(description) or '—'} | {', '.join(f'`{cell(host)}`' for host in sorted(hosts))} | [`{cell(declaration)}`](../{declaration}) |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in inventory is stale")
    args = parser.parse_args()
    expression = f"(import {ROOT / 'scripts/docs/inventory.nix'}) (builtins.getFlake {json.dumps('git+file:' + str(ROOT))})"
    result = subprocess.run(
        ["nix", "eval", "--impure", "--json", "--no-write-lock-file", "--expr", expression],
        cwd=ROOT, check=True, text=True, stdout=subprocess.PIPE,
    )
    generated = render(json.loads(result.stdout))
    if args.check:
        current = DOCUMENT.read_text() if DOCUMENT.exists() else ""
        if current != generated:
            sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), generated.splitlines(True), fromfile="docs/apps.md", tofile="generated inventory"))
            print("Inventory is stale; run make inventory and include docs/apps.md.", file=sys.stderr)
            return 1
        print("Package inventory is synchronized with Nix declarations.")
    else:
        DOCUMENT.write_text(generated)
        print("Updated docs/apps.md from evaluated Nix declarations.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
