#!/usr/bin/env python3
"""Render the declared APM skill inventory without fetching upstream content."""

import argparse
import difflib
from pathlib import Path, PurePosixPath
import sys
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parents[2]
DOCUMENT = ROOT / "docs/skills.md"


def cell(value):
    return " ".join(value.split()).replace("&", "&amp;").replace("|", "&#124;").replace("<", "&lt;").replace(">", "&gt;").replace("`", "&#96;")


def render(manifest):
    rows = []
    for dependency in manifest["dependencies"]["apm"]:
        path = dependency.get("path", "")
        if "git" not in dependency:
            name = dependency.get("alias") or PurePosixPath(path).name
            if not name:
                raise ValueError("A skill dependency needs a path or alias")
            source = f"../{path.removeprefix('./')}"
            rows.append((name, "local", path, "—", "—", source, "local"))
            continue
        repository = dependency["git"].removesuffix(".git")
        ref = dependency["ref"]
        # Explicit selectors describe package exports, not necessarily repository paths.
        names = dependency.get("skills") or [dependency.get("alias") or PurePosixPath(path).name]
        if not all(names):
            raise ValueError("A skill dependency needs a path, alias, or explicit skills selector")
        source = f"{repository}/tree/{quote(ref, safe='')}"
        if path:
            source += f"/{quote(path, safe='/')}"
        selection = ", ".join(dependency.get("skills", [])) or "—"
        for name in names:
            rows.append((name, repository, path or ".", ref, selection, source, "upstream"))
    lines = [
        "# Declared agent skills", "",
        "Generated from [`apm.yml`](../apm.yml). Do not edit this file by hand.", "",
        "Regenerate with `make skills`; verify with `make skills-check`.", "",
        "This is the repository's desired APM inventory, not a list of currently installed skills.",
        "Names use explicit skill selectors, then aliases, then the final path component.",
        "Source links use the declared ref and package path; selectors identify package exports,",
        "not inferred repository directories. See [APM management](apm.md) for deployment and updates.", "",
        f"Declared skills: {len(rows)}.", "",
        "| Skill | Repository | Package path | Ref | Skill selector | Source |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for name, repository, path, ref, selection, source, source_label in sorted(rows):
        lines.append(f"| `{cell(name)}` | {cell(repository)} | `{cell(path)}` | `{cell(ref)}` | {cell(selection)} | [{source_label}]({source}) |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in skill inventory is stale")
    args = parser.parse_args()
    generated = render(yaml.safe_load((ROOT / "apm.yml").read_text()))
    if args.check:
        current = DOCUMENT.read_text() if DOCUMENT.exists() else ""
        if current != generated:
            sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), generated.splitlines(True), fromfile="docs/skills.md", tofile="generated skill inventory"))
            print("Skill inventory is stale; run make skills and include docs/skills.md.", file=sys.stderr)
            return 1
        print("Skill inventory is synchronized with apm.yml.")
    else:
        DOCUMENT.write_text(generated)
        print("Updated docs/skills.md from apm.yml.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
